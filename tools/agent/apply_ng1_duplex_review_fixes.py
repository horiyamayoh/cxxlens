sigpipe_helper = r'''

		/**
		 * A pipe write reports EPIPE and generates SIGPIPE in the calling thread.  A library
		 * transport must not change the process-wide signal disposition, so block SIGPIPE only
		 * around this write and consume the signal generated by this call before restoring the
		 * caller's mask.  A SIGPIPE that was already pending remains pending.
		 */
		[[nodiscard]] ssize_t write_without_sigpipe(const int destination,
												 const void* const data,
												 const std::size_t size) noexcept
		{
			sigset_t blocked{};
			sigset_t previous{};
			if (::sigemptyset(&blocked) != 0 || ::sigaddset(&blocked, SIGPIPE) != 0)
				return -1;
			const auto block_error = ::pthread_sigmask(SIG_BLOCK, &blocked, &previous);
			if (block_error != 0)
			{
				errno = block_error;
				return -1;
			}

			sigset_t pending{};
			if (::sigpending(&pending) != 0)
			{
				const auto pending_error = errno;
				(void)::pthread_sigmask(SIG_SETMASK, &previous, nullptr);
				errno = pending_error;
				return -1;
			}
			const bool already_pending = ::sigismember(&pending, SIGPIPE) == 1;
			const auto written = ::write(destination, data, size);
			const auto write_error = written < 0 ? errno : 0;
			if (written < 0 && write_error == EPIPE && !already_pending)
			{
				timespec immediate{};
				while (::sigtimedwait(&blocked, nullptr, &immediate) < 0 && errno == EINTR)
				{
				}
			}
			const auto restore_error = ::pthread_sigmask(SIG_SETMASK, &previous, nullptr);
			if (restore_error != 0)
			{
				errno = restore_error;
				return -1;
			}
			if (written < 0)
				errno = write_error;
			return written;
		}
'''
