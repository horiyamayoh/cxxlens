new_reap_and_kill = r'''			void reap_nonblocking() noexcept
			{
				// Keep the group leader waitable while a descendant may still retain an output pipe.
				// This preserves a stable process-group identity for timeout and cancellation cleanup.
				if (reaped_ || child_ <= 0 || !stdout_ended_ || !stderr_ended_)
					return;
				const auto waited = ::waitpid(child_, &wait_status_, WNOHANG);
				if (waited == child_ || (waited < 0 && errno == ECHILD))
					reaped_ = true;
			}

			void kill_process_group() noexcept
			{
				if (child_ <= 0)
					return;
				const auto signal_deadline =
					std::chrono::steady_clock::now() + std::chrono::milliseconds{100};
				for (;;)
				{
					if (::kill(-child_, SIGKILL) != 0 && errno == ESRCH)
						break;
					if (std::chrono::steady_clock::now() >= signal_deadline)
						break;
					std::this_thread::sleep_for(std::chrono::milliseconds{1});
				}
				if (!reaped_)
				{
					for (;;)
					{
						const auto waited = ::waitpid(child_, &wait_status_, 0);
						if (waited == child_ || (waited < 0 && errno == ECHILD))
						{
							reaped_ = true;
							break;
						}
						if (waited < 0 && errno == EINTR)
							continue;
						break;
					}
				}
			}
'''
source = replace_regex(
    source,
    r"\t\t\tvoid reap_nonblocking\(\) noexcept\n\t\t\t\{.*?\n\t\t\t\}\n\n\t\t\tvoid kill_process_group\(\) noexcept\n\t\t\t\{.*?\n\t\t\t\}(?=\n\n\t\t\tdescriptor input_)",
    new_reap_and_kill,
    "reap and kill",
)
